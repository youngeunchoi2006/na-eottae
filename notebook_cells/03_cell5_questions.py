def pick(pattern, date):
    """법안명에 pattern이 있고, 처리일 또는 표결일이 date인 법안의 BILL_ID (date: '2025-08-25' 또는 '20250825')"""
    d = date.replace('-', '')
    ids = bills.loc[bills['BILL_NM'].str.contains(pattern, na=False, regex=True), 'BILL_ID']
    ids = [i for i in ids if proc_dates.get(i, '').replace('-', '').startswith(d)
           or vote_dates.get(i, '').replace('-', '').startswith(d)]
    assert len(ids) == 1, f'{pattern} / {date} → {len(ids)}건 찾음, 조건을 확인하세요'
    return ids[0]

